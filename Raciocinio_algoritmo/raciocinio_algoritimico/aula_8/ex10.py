# 10. O que acontece em: apresentar('Ana', 'Curitiba', 20)?

def presentar(nome, idade, cidade):
    print("Nome: ", nome, "\n")
    print("Idade: ", idade, "\n")
    print("Cidade: ", cidade), "\n"

presentar('Ana', 'Curitiba', 20)


# O código vai imprimir
# Nome:  Kauê

# Idade:  Curitiba

# Cidade:  20
